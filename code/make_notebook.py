"""Build and execute the analysis notebook from code/wastewater_analysis.py.

The notebook is generated from the script, so the two can never disagree:
  - each "# %%" cell of the script becomes a notebook section;
  - a highlighted box above each section states which research question (RQ),
    objective (Obj) and requirement (R) it answers, as the supervisor asked
    (feedback of 3 Oct 2026); the same tags open each code cell as a comment;
  - each INSIGHT comment becomes a highlighted note under the section's results;
  - the notebook is executed from a fresh kernel, so every output shown is real.

Usage (from the project folder):   python code/make_notebook.py
Output: notebooks/Wastewater_Analysis.ipynb (executed)
"""
import re
from pathlib import Path

import nbformat
from nbclient import NotebookClient

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "code" / "wastewater_analysis.py"
OUT = ROOT / "notebooks" / "Wastewater_Analysis.ipynb"

# What each script section answers: (research questions, objectives, requirements).
TAGS = {
    0: ("Supports RQ1-RQ3", "Objective 6", "R11 (method self-tests)"),
    1: ("RQ1", "Objective 1", "R01, R02, R04"),
    2: ("RQ3 (comparison measure)", "Objectives 1, 4", "R02, R03"),
    3: ("RQ1", "Objective 1", "R01, R05"),
    4: ("RQ1-RQ3", "Objective 1", "R03, R04, R05"),
    5: ("RQ1", "Objective 2", "R06"),
    6: ("RQ2 (main models) and RQ3 (sensitivity)", "Objectives 3, 4", "R07, R08"),
    7: ("RQ1-RQ3", "Objectives 2, 5", "R06"),
    8: ("RQ4", "Objective 5", "R09, R10"),
    9: ("RQ1-RQ4", "Objective 6", "R02, R11"),
}


def box(kind, title, body):
    """Highlighted box: coloured in Jupyter (alert classes), readable as plain text on GitHub."""
    return f'<div class="alert alert-block alert-{kind}">\n\n**{title}**\n\n{body}\n\n</div>'


def split_cells(text):
    """Return the module docstring and a list of (number, title, code) for each '# %%' cell."""
    doc = re.match(r'"""(.*?)"""', text, re.S).group(1).strip()
    parts = re.split(r"^# %% ", text, flags=re.M)[1:]
    cells = []
    for part in parts:
        header, _, code = part.partition("\n")
        number = int(header.split(".")[0])
        title = re.sub(r"\s*-+\s*$", "", header.split(". ", 1)[1]).strip()
        title = re.sub(r"\s+--\s+R\d\d.*$", "", title)        # requirement codes go in the box instead
        cells.append((number, title, code.strip("\n")))
    return doc, cells


def split_insight(code):
    """Separate trailing INSIGHT comment blocks from the code."""
    lines = code.splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith("# INSIGHT")), None)
    if start is None:
        return code, None
    insight = "\n".join(re.sub(r"^# ?", "", l) for l in lines[start:] if l.startswith("#"))
    insight = re.sub(r"^INSIGHT \(([^)]*)\)[:.]?", r"*(\1)*", insight, flags=re.M)   # keep the qualifier
    insight = re.sub(r"^INSIGHT:\s*", "", insight, flags=re.M)
    return "\n".join(lines[:start]).rstrip(), insight


def build():
    doc, cells = split_cells(SCRIPT.read_text(encoding="utf-8"))
    nb = nbformat.v4.new_notebook()
    nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
    nb.cells.append(nbformat.v4.new_markdown_cell(
        "# Wastewater base spending and operational performance\n\n"
        "Executed version of `code/wastewater_analysis.py` (generated by `code/make_notebook.py`). "
        "Blue boxes state which research question, objective and requirement each section answers; "
        "green boxes give the insight drawn from that section's results.\n\n```text\n" + doc + "\n```"))
    nb.cells.append(nbformat.v4.new_code_cell(
        "# Notebook set-up: tell the script where it lives, so its relative paths work.\n"
        "from pathlib import Path\n"
        "__file__ = str(Path.cwd().parent / 'code' / 'wastewater_analysis.py')"))
    for number, title, code in cells:
        rq, obj, req = TAGS[number]
        nb.cells.append(nbformat.v4.new_markdown_cell(
            f"## {number}. {title}\n\n" + box("info", "Answers", f"{rq} · {obj} · Requirements {req}")))
        code, insight = split_insight(code)
        tag = f"# Answers {rq} | {obj} | Requirements {req}\n"
        nb.cells.append(nbformat.v4.new_code_cell(tag + code))
        if number == 7:
            nb.cells.append(nbformat.v4.new_code_cell(
                "# Show the figures written above\nfrom IPython.display import Image, display\n"
                "for name in ['fig_outcome_coverage.png', 'fig_company_trends.png', 'fig_association_estimates.png']:\n"
                "    display(Image(filename=str(FIG / name)))"))
        if insight:
            nb.cells.append(nbformat.v4.new_markdown_cell(box("success", "Insight", insight)))
    return nb


if __name__ == "__main__":
    OUT.parent.mkdir(exist_ok=True)
    notebook = build()
    NotebookClient(notebook, timeout=1800, kernel_name="python3",
                   resources={"metadata": {"path": str(OUT.parent)}}).execute()
    nbformat.write(notebook, OUT)
    errors = [c for c in notebook.cells if c.cell_type == "code"
              for o in c.get("outputs", []) if o.get("output_type") == "error"]
    print(f"Written {OUT.relative_to(ROOT)}: {len(notebook.cells)} cells, errors: {len(errors)}")
